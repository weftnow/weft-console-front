// Generates matching-simulation pairs for the themed demo rosters in public/demo (one fixture per roster).
// Deterministic (seeded). Run: node scripts/generate-demo-event-matches.mjs
// Writes src/modules/network/simulation/demo-event-matches-generated.ts.
import { readFileSync, writeFileSync } from "node:fs";
import { parse } from "csv-parse/sync";
import { buildPairs } from "./demo-pairs.mjs";

const ROSTERS = [
  { id: "ai-summit", file: "public/demo/weft-demo-ai-summit-300.csv", seed: 20261026 },
  { id: "grand-prix", file: "public/demo/weft-demo-grand-prix-400.csv", seed: 20261027 },
];
const PAIRS = 99; // the simulator's per-fixture cap

const fixtures = {};
for (const roster of ROSTERS) {
  let seed = roster.seed;
  const random = () => { seed = (seed + 0x6d2b79f5) | 0; let t = Math.imul(seed ^ (seed >>> 15), 1 | seed); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  const shuffle = (list) => { const copy = [...list]; for (let i = copy.length - 1; i > 0; i -= 1) { const j = Math.floor(random() * (i + 1)); [copy[i], copy[j]] = [copy[j], copy[i]]; } return copy; };
  const rows = parse(readFileSync(roster.file, "utf8"), { bom: true, trim: true }).slice(1);
  if (rows.some((cells) => cells.length !== 9)) throw new Error(`${roster.file} has a row with missing fields`);
  const guests = rows.map((cells) => ({ first: cells[0], last: cells[1], email: cells[2].toLowerCase(), company: cells[4], position: cells[5], profile: cells[7], type: cells[8] }));
  fixtures[roster.id] = buildPairs(guests, PAIRS, { random, shuffle });
  const perGuest = new Map(); for (const pair of fixtures[roster.id]) for (const email of [pair.a, pair.b]) perGuest.set(email, (perGuest.get(email) ?? 0) + 1);
  console.log(`${roster.id}: ${guests.length} guests, ${PAIRS} pairs over ${perGuest.size} guests, max ${Math.max(...perGuest.values())} each`);
}
writeFileSync("src/modules/network/simulation/demo-event-matches-generated.ts", `// Generated by scripts/generate-demo-event-matches.mjs for the themed rosters in public/demo. Do not edit by hand.\nimport type { DemoMatch } from "./demo-matches";\n\nexport const DEMO_EVENT_FIXTURES: Readonly<Record<string, readonly DemoMatch[]>> = ${JSON.stringify(fixtures, null, 2)};\n`);
