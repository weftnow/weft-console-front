export const reportingCopyByLocale = {
  en: enCopy,
  es: esCopy,
} as const;

export function getReportingCopy(locale: ReportingLocale): typeof enCopy | typeof esCopy {
  return locale === "es" ? esCopy : enCopy;
}

export function interpolate(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

function humanizeFallback(key: string): string {
  const spaced = key
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .trim();
  if (!spaced) return key;
  return spaced.charAt(0).toUpperCase() + spaced.slice(1);
}

export function localizeKey(locale: ReportingLocale, key: string): string {
  const copy = getReportingCopy(locale);
  const direct = Object.hasOwn(copy.labels, key) ? copy.labels[key] : undefined;
  if (direct) return direct;
  const normalized = key.trim().toLowerCase();
  const lowered = Object.hasOwn(copy.labels, normalized) ? copy.labels[normalized] : undefined;
  if (lowered) return lowered;
  return humanizeFallback(key);
}

export function localizeLabel(locale: ReportingLocale, label: ReportLabel): string {
  if ("text" in label) return label.text;
  if ("date" in label) return formatDate(locale, label.date, { dateStyle: "medium" }, label.timezone);
  return localizeKey(locale, label.key);
}

export function formatCount(locale: ReportingLocale, value: number): string {
  return formatNumber(locale, value, { maximumFractionDigits: 0 });
}

export function formatPercent(locale: ReportingLocale, value: number): string {
  const rounded = Math.round(value * 10) / 10;
  return formatNumber(locale, rounded / 100, {
    style: "percent",
    maximumFractionDigits: Number.isInteger(rounded) ? 0 : 1,
  });
}

export function formatRatio(locale: ReportingLocale, value: ReportCount): string {
  const copy = getReportingCopy(locale);
  if (typeof value.total === "number") {
    return interpolate(copy.units.ratio, {
      count: formatCount(locale, value.count),
      total: formatCount(locale, value.total),
    });
  }
  return formatCount(locale, value.count);
}

export function computeRateFromCount(value: ReportCount): number | null {
  if (typeof value.total !== "number" || value.total <= 0) return null;
  return (value.count / value.total) * 100;
}

export function formatDeltaPoints(locale: ReportingLocale, delta: number): {
  text: string;
  ariaLabel: string;
} {
  const copy = getReportingCopy(locale);
  const rounded = Math.round(delta * 10) / 10;
  const formatted = formatNumber(locale, rounded, {
    signDisplay: rounded === 0 ? "auto" : "exceptZero",
    maximumFractionDigits: Number.isInteger(rounded) ? 0 : 1,
  });
  return {
    text: interpolate(copy.units.percentagePoints, { value: formatted }),
    ariaLabel: interpolate(copy.units.percentagePointsAria, { value: formatted }),
  };
}

export function formatShortDate(locale: ReportingLocale, iso: string): string {
  try {
    return formatDate(locale, iso, { day: "numeric", month: "short", year: "numeric" });
  } catch {
    return iso;
  }
}

export function getViewLabel(locale: ReportingLocale, view: ReportView): string {
  return getReportingCopy(locale).views[view];
}

export function getTrendMetricLabel(locale: ReportingLocale, metric: TrendMetric): string {
  return getReportingCopy(locale).reports[metric].shortTitle;
}
